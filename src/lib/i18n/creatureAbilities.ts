/** Localizes a single `abilities` enum key (e.g. "two_retaliations"). */
export function localizeCreatureAbility(ability: string, locale: Locale): string {
  if (locale !== "fr") return ability.replace(/_/g, " ");
  return ABILITY_FR[ability] ?? ability.replace(/_/g, " ");
}

/** Localizes and joins a creature's `abilities` array for display. */
export function localizeCreatureAbilities(abilities: readonly string[], locale: Locale): string {
  return abilities.map((ability) => localizeCreatureAbility(ability, locale)).join(", ");
}

/** Localizes a creature's free-text `special` string fragment-by-fragment. */
export function localizeCreatureSpecial(special: string, locale: Locale): string {
  if (locale !== "fr") return special;
  return special
    .split(",")
    .map((fragment) => {
      const trimmed = fragment.trim();
      return SPECIAL_FRAGMENT_FR[trimmed] ?? trimmed;
    })
    .join(", ");
}
